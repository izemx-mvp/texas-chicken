let lang: Lang = "fr";
const listeners = new Set<() => void>();

if (typeof window !== "undefined") {
  const stored = window.localStorage.getItem(KEY) as Lang | null;
  if (stored && LANGUAGES.some((l) => l.value === stored)) lang = stored;
}

export function setLang(next: Lang) {
  if (next === lang) return;
  lang = next;
  if (typeof window !== "undefined") {
    window.localStorage.setItem(KEY, next);
    document.documentElement.lang = next;
    // L'arabe reste en lecture gauche-droite : pas de dir="rtl".
    document.documentElement.dir = "ltr";
    // Rechargement pour appliquer proprement la traduction à toute l'application.
    window.location.reload();
    return;
  }
  listeners.forEach((l) => l());
}

export function getLang() {
  return lang;
}

/** Traduit une clé ; repli sur le français si la traduction manque. */
export function translate(key: string, current: Lang = lang) {
  const fr = FR[key];
  if (!fr) return tr(key, current);
  return tr(fr, current);
}

/** Traduit une phrase française affichée telle quelle dans l'interface. */
export function tr(text: string, current: Lang = lang) {
  if (current === "fr" || !text) return text;
  const trimmed = text.trim();
  const hit = P[trimmed];
  if (!hit) return text;
  const value = current === "en" ? hit[0] : hit[1];
  // Conserve les espaces autour du texte (important dans le DOM).
  return text.replace(trimmed, value);
}

/** Vrai si la phrase possède une traduction (utilisé par la traduction du DOM). */
export function hasPhrase(text: string) {
  return Boolean(P[text.trim()]);
}

export function useLang() {
  const current = useSyncExternalStore(
    (l) => {
      listeners.add(l);
      return () => listeners.delete(l);
    },
    () => lang,
    () => "fr" as Lang,
  );
  return {
    lang: current,
    setLang,
    t: (key: string) => translate(key, current),
    tr: (text: string) => tr(text, current),
  };
}
